"""Records the README's GIFs from the example app on macOS.

Runs tool/media/media_app.dart (the example gallery, with time set from
outside) under `flutter run --machine`, and drives it the way the DevTools
extension does: probes generated by tool/make_probe.dart, written into
shaders/_debug/probe.frag and hot reloaded, then the ext.shader_debugger.*
service extensions. Frames come from the app's own layer tree through
ext.media.capture (no screen recording), and ffmpeg turns them into GIFs in
doc/media/. The placeholder probe is restored at the end.

Usage, from the repo root, with the example app not running already:
    python3 tool/readme_media.py            # record, then encode
    python3 tool/readme_media.py --encode   # encode the last recording again

The frames stay in build/readme_media/ (git-ignored), so the GIFs can be
encoded again with other settings without recording.
"""
import base64
import colorsys
import json
import math
import os
import queue
import shutil
import subprocess
import sys
import threading
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXAMPLE = os.path.join(ROOT, 'packages', 'shader_debugger', 'example')
PROBE = os.path.join(EXAMPLE, 'shaders', '_debug', 'probe.frag')
MEDIA = os.path.join(ROOT, 'doc', 'media')
GRADIENT = 'shaders/gradient.frag'
LIGHTS = 'shaders/lights.frag'
FPS = 15
WIDTH = 640  # GIF width in pixels

placeholder = open(PROBE).read()
frames_root = os.path.join(ROOT, 'build', 'readme_media')
events = queue.Queue()
next_id = [0]
app_id = None

proc = None


def start_app():
    """Starts the media app under `flutter run --machine`."""
    global proc
    proc = subprocess.Popen(
        ['flutter', 'run', '-d', 'macos', '--machine', '-t', '../../../tool/media/media_app.dart'],
        cwd=EXAMPLE, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT, text=True, bufsize=1)

    def pump():
        for line in proc.stdout:
            line = line.strip()
            if line.startswith('[{') and line.endswith('}]'):
                events.put(json.loads(line)[0])

    threading.Thread(target=pump, daemon=True).start()


def wait(predicate, timeout=300):
    end = time.time() + timeout
    while time.time() < end:
        try:
            message = events.get(timeout=1)
        except queue.Empty:
            continue
        if predicate(message):
            return message
    raise TimeoutError('no answer from flutter run')


def call(method, params, timeout=300):
    next_id[0] += 1
    request_id = next_id[0]
    proc.stdin.write(json.dumps([{'id': request_id, 'method': method, 'params': params}]) + '\n')
    proc.stdin.flush()
    return wait(lambda m: m.get('id') == request_id, timeout)


def extension(method, /, **params):
    message = call('app.callServiceExtension', {
        'appId': app_id,
        'methodName': method,
        'params': {key: str(value) for key, value in params.items()},
    })
    if 'error' in message:
        raise RuntimeError('%s: %s' % (method, message['error']))
    return message.get('result') or {}


def media(name, /, **params):
    return extension('ext.media.' + name, **params)


def debugger(name, /, **params):
    return extension('ext.shader_debugger.' + name, **params)


stamps = [100]


def show_heatmap(asset, line, expression, low=0.0, high=1.0):
    """Generates the probe, hot reloads it in, and shows it."""
    stamps[0] += 1
    stamp = stamps[0]
    shader = os.path.join(EXAMPLE, asset)
    source = subprocess.run(
        ['dart', '--packages=' + os.path.join(ROOT, '.dart_tool', 'package_config.json'),
         os.path.join(ROOT, 'tool', 'make_probe.dart'), shader, str(line), expression, str(stamp)],
        capture_output=True, text=True, check=True).stdout
    open(PROBE, 'w').write(source)
    reload = call('app.restart', {'appId': app_id, 'fullRestart': False, 'pause': False})
    if (reload.get('result') or {}).get('code') != 0:
        raise RuntimeError('hot reload failed: %s' % reload)
    for _ in range(25):
        if debugger('showHeatmap', asset=asset, stamp=stamp, min=low, max=high).get('applied'):
            return stamp
        time.sleep(0.2)
    raise RuntimeError('the probe for %s never loaded' % expression)


class Recording:
    """Frames of one GIF, at FPS, with time stepping along."""

    def __init__(self, name, region, start=0.0):
        self.name = name
        self.region = region
        self.directory = os.path.join(frames_root, name)
        shutil.rmtree(self.directory, ignore_errors=True)
        os.makedirs(self.directory)
        self.count = 0
        self.t = start

    def frame(self, hold=1, animate=True):
        """Captures the next frame, shown for `hold` frames; with `animate`,
        time moves on by as much."""
        media('time', t=self.t)
        png = base64.b64decode(media('capture', **self.region)['png'])
        for _ in range(hold):
            with open(os.path.join(self.directory, '%04d.png' % self.count), 'wb') as f:
                f.write(png)
            self.count += 1
        if animate:
            self.t += hold / FPS
        return png

    def seconds(self, seconds, animate=True):
        for _ in range(int(seconds * FPS)):
            self.frame(animate=animate)

    def gif(self):
        encode(self.name)


def encode(name):
    """Turns build/readme_media/<name>/ into doc/media/<name>.gif. Smooth
    gradients need error diffusion, not ordered dithering, to avoid bands."""
    os.makedirs(MEDIA, exist_ok=True)
    out = os.path.join(MEDIA, name + '.gif')
    graph = ('scale=%d:-1:flags=lanczos,split[a][b];'
             '[a]palettegen=max_colors=256:stats_mode=full[p];'
             '[b][p]paletteuse=dither=sierra2_4a') % WIDTH
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-framerate', str(FPS),
                    '-i', os.path.join(frames_root, name, '%04d.png'),
                    '-vf', graph, '-loop', '0', out], check=True)
    print('wrote %s (%.1f MB)' % (out, os.path.getsize(out) / 1e6))


if '--encode' in sys.argv:
    for name in ['heatmap', 'pixel-select', 'uniforms']:
        encode(name)
    sys.exit(0)


def path_point(area, u, v):
    """The point at fractions (u, v) of a painted area."""
    return (area['left'] + u * area['width'], area['top'] + v * area['height'])


start_app()
try:
    app_id = wait(lambda m: m.get('event') == 'app.started')['params']['appId']
    for _ in range(100):
        try:
            layout = media('layout')
            break
        except RuntimeError:
            time.sleep(0.2)
    stage = layout['stage']
    gradient = layout['painted'][GRADIENT]
    print('stage %(width)gx%(height)g' % stage, 'ratio', layout['ratio'])

    # 1. Heatmaps: d in the gradient, its range, then a value in a loop.
    heatmap = Recording('heatmap', stage, start=0.5)
    heatmap.seconds(1.2)
    show_heatmap(GRADIENT, 15, 'd', 0.0, 0.71)
    heatmap.seconds(1.4)
    for i in range(int(2.4 * FPS)):
        high = 0.71 - 0.4 * math.sin(math.pi * i / (2.4 * FPS))
        debugger('showHeatmap', asset=GRADIENT, stamp=stamps[0], min=0, max=high)
        heatmap.frame()
    show_heatmap(LIGHTS, 34, 'falloff')
    heatmap.seconds(3.0)
    heatmap.gif()
    debugger('hideHeatmap')

    # 2. Pixel select mode: hover, click, read.
    debugger('setPixelSelectMode', enabled='true', asset=GRADIENT)
    select = Recording('pixel-select', stage, start=1.0)
    for i in range(int(2.2 * FPS)):
        a = 2 * math.pi * i / (2.2 * FPS)
        x, y = path_point(gradient, 0.5 + 0.3 * math.cos(a), 0.5 + 0.25 * math.sin(2 * a))
        media('hover', x=x, y=y)
        select.frame(animate=False)
    x, y = path_point(gradient, 0.72, 0.35)
    media('hover', x=x, y=y)
    select.frame(animate=False)
    media('click', x=x, y=y)
    select.frame(hold=int(0.8 * FPS), animate=False)
    for i in range(int(1.0 * FPS)):
        f = i / (1.0 * FPS)
        x, y = path_point(gradient, 0.72 - 0.4 * f, 0.35 + 0.35 * f)
        media('hover', x=x, y=y)
        select.frame(animate=False)
    media('click', x=x, y=y)
    select.frame(hold=int(1.2 * FPS), animate=False)
    select.gif()
    debugger('setPixelSelectMode', enabled='false')

    # 3. Uniform overrides: the gradient's colors, swept.
    uniforms = Recording('uniforms', stage, start=2.0)
    uniforms.seconds(0.8)
    for i in range(int(3.2 * FPS)):
        hue = i / (3.2 * FPS)
        a = colorsys.hsv_to_rgb(hue, 0.85, 0.95)
        b = colorsys.hsv_to_rgb((hue + 0.45) % 1, 0.8, 1.0)
        debugger('setUniformOverride', asset=GRADIENT, name='uA', values='%f,%f,%f,1' % a)
        debugger('setUniformOverride', asset=GRADIENT, name='uB', values='%f,%f,%f,1' % b)
        uniforms.frame()
    debugger('clearUniformOverrides', asset=GRADIENT)
    uniforms.seconds(0.8)
    uniforms.gif()

    # A still of the gallery.
    still = Recording('gallery', stage, start=1.3)
    png = still.frame(animate=False)
    with open(os.path.join(MEDIA, 'gallery.png'), 'wb') as f:
        f.write(png)
finally:
    open(PROBE, 'w').write(placeholder)
    if app_id:
        try:
            call('app.stop', {'appId': app_id}, timeout=30)
        except Exception as error:  # noqa: BLE001
            print('could not stop the app: %s' % error)
    proc.terminate()
    try:
        proc.wait(timeout=20)
    except subprocess.TimeoutExpired:
        proc.kill()
